export function getRoleAdjustedStep(
  step: WalkthroughStep,
  roleId: OrgRoleId | null
): WalkthroughStep {
  if (!roleId || !step.roleOverrides?.[roleId]) {
    return step;
  }
  const override = step.roleOverrides[roleId]!;
  return {
    ...step,
    title: override.title || step.title,
    shortTitle: override.shortTitle || step.shortTitle,
    category: override.category || step.category,
    script: override.script || step.script,
    keyPoints: override.keyPoints || step.keyPoints,
    suggestedAction: override.suggestedAction || step.suggestedAction,
    actionButtonLabel: override.actionButtonLabel || step.actionButtonLabel,
  };
}

export function getRoleById(roleId: OrgRoleId | null): OrgRole {
  const found = ORGANIZATION_ROLES.find((r) => r.id === roleId);
  return found || ORGANIZATION_ROLES[0];
}

